#!/usr/bin/env python3
"""Reference for the room on headphones (round 3B-3a).

Writes tests/vectors/room.vec. tests/sc/check_room.scd checks the patch's
own ~manifold[\\speakerAt] and ~manifold[\\hear] against every line.

Worked out here another way than the patch: the listener as two unit
vectors -- forward and to the right, turned by `facing` -- and a speaker's
direction as a unit vector; the azimuth from its components along them, the
side the sound is on (the lateral angle) from its component along the ears'
axis, and "behind" from its component along forward -- not from the azimuth
and elevation's sines and cosines.

    HEAR name placed x y z | heights | width depth height facing
        EXPECT az el dist gain delayL delayR gainL gainR shelfL shelfR notch air wet

`gain` (3B-3b): the distance's level alone, before either ear -- what the
ATK's room uses, its ears its own.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "vectors", "room.vec")

HEAD = 0.0875          # the head's radius, metres
SOUND = 343.0          # metres a second


def f(x):
    return f"{x:.9g}"


def speaker_at(placed, x, y, z, heights, size):
    """(right, ahead, up) in metres from the listener, or None: inside."""
    if not placed:
        return None
    lo, hi = min(heights), max(heights)
    up = ((z - lo) / (hi - lo) - 0.5) * size[2] if hi > lo else 0.0
    return ((x - 0.5) * size[0], (y - 0.5) * size[1], up)


def hear(at, facing):
    t = math.radians(facing)
    forward = (math.sin(t), math.cos(t), 0.0)
    right = (math.cos(t), -math.sin(t), 0.0)
    if at is None:
        az = el = 0.0
        dist = 1.0
        side = 0.0          # the component along the ears' axis, as a sine
        ahead = 1.0         # along forward
    else:
        dist = math.sqrt(sum(c * c for c in at))
        along_f = sum(a * b for a, b in zip(at, forward))
        along_r = sum(a * b for a, b in zip(at, right))
        flat = math.hypot(along_f, along_r)
        az = math.atan2(along_r, along_f) if flat > 0 else 0.0
        el = math.asin(at[2] / dist) if dist > 0 else 0.0
        side = along_r / dist if dist > 0 else 0.0
        ahead = along_f / dist if dist > 0 else 1.0
    dist = max(dist, 0.3)
    lat = math.asin(max(-1.0, min(1.0, side)))
    itd = HEAD / SOUND * (abs(lat) + math.sin(abs(lat)))
    far = 10 ** (-6 * math.sin(abs(lat)) / 20)
    shade = -12 * math.sin(abs(lat))
    behind = -5 * max(0.0, -ahead)
    gain = min(1.0, 2 / dist) * math.sqrt(0.5)
    right_side = lat > 0
    left_side = lat < 0
    return (az, el, dist, gain,
            itd if right_side else 0.0, itd if left_side else 0.0,
            gain * (far if right_side else 1.0), gain * (far if left_side else 1.0),
            behind + (shade if right_side else 0.0), behind + (shade if left_side else 0.0),
            6000 * 2 ** (0.75 * el / (math.pi / 2)),
            20000 * 0.93 ** dist,
            dist / (dist + 3))


def main():
    out = [
        "# ofxManifold -- the room on headphones (round 3B-3a)",
        "# Generated by tests/ref/reference_room.py -- do not edit.",
        "#",
        "# HEAR name placed x y z | heights | width depth height facing",
        "#     EXPECT az el dist gain delayL delayR gainL gainR shelfL shelfR notch air wet",
        "",
    ]
    n = 0
    room = (0.0, 0.25, 0.5)          # the room example's three levels
    octa = (-0.5, 0.5)               # the octahedron's two
    size = (8.0, 8.0, 4.0)

    def case(name, placed, x, y, z, heights=room, sz=size, facing=0.0):
        nonlocal n
        h = hear(speaker_at(placed, x, y, z, heights, sz), facing)
        out.append(f"HEAR {name} {int(placed)} {f(x)} {f(y)} {f(z)} | "
                   + " ".join(f(v) for v in heights) + " | "
                   + " ".join(f(v) for v in sz) + f" {f(facing)} EXPECT "
                   + " ".join(f(v) for v in h))
        n += 1

    # Around the listener, on the ears' level (the middle of three).
    case("left", True, 0.1, 0.5, 0.25)
    case("right", True, 0.9, 0.5, 0.25)
    case("ahead", True, 0.5, 0.9, 0.25)
    case("behind", True, 0.5, 0.1, 0.25)
    case("ahead_left", True, 0.2, 0.8, 0.25)
    case("behind_right", True, 0.8, 0.2, 0.25)
    case("near_right", True, 0.6, 0.5, 0.25)
    # Above and below: the top level and the floor.
    case("overhead", True, 0.5, 0.5, 0.5)
    case("underfoot", True, 0.5, 0.5, 0.0)
    case("ahead_up", True, 0.5, 0.8, 0.5)
    case("ahead_down", True, 0.5, 0.8, 0.0)
    # The room example's corners on each level.
    for lvl, z in (("floor", 0.0), ("middle", 0.25), ("top", 0.5)):
        for name, x, y in (("FL", 0.2, 0.8), ("FR", 0.8, 0.8), ("RL", 0.2, 0.2), ("RR", 0.8, 0.2)):
            case(f"{name}_{lvl}", True, x, y, z)
    # Turned: right a quarter, and right round.
    case("ahead_facing_right", True, 0.5, 0.9, 0.25, facing=90.0)
    case("left_facing_right", True, 0.1, 0.5, 0.25, facing=90.0)
    case("ahead_turned_round", True, 0.5, 0.9, 0.25, facing=180.0)
    case("left_turned_round", True, 0.1, 0.5, 0.25, facing=180.0)
    case("FR_facing_left", True, 0.8, 0.8, 0.5, facing=-45.0)
    # No place: inside the head, whatever its numbers.
    case("unplaced", False, 0.9, 0.1, 0.5)
    # One level: everything at the ears' height.
    case("one_level", True, 0.2, 0.8, 0.0, heights=(0.0,))
    # At the listener: held 0.3 m off.
    case("at_the_ears", True, 0.5, 0.5, 0.25)
    # The octahedron: its rim on neither level, halfway up.
    case("octahedron_rim", True, 0.8, 0.5, 0.0, heights=octa)
    case("octahedron_top", True, 0.5, 0.5, 0.5, heights=octa)
    # Another room: small and low, and long.
    case("small_room", True, 0.1, 0.9, 0.5, sz=(3.0, 3.0, 2.5))
    case("long_room", True, 0.5, 1.0, 0.25, sz=(4.0, 30.0, 4.0))

    with open(OUT, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"room.vec: {n} vectors")


if __name__ == "__main__":
    main()
